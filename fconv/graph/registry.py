def _sips_edge(
    source: str,
    target: str,
    cost: int,
    fidelity: FidelityClass,
    description: str,
    *,
    sips_fmt: str = "",
    is_fallback: bool = False,
    terminal_only: bool = False,
    supports_dpi: bool = True,
) -> Edge:
    fmt = sips_fmt or target
    return Edge(
        source=source,
        target=target,
        engine_name="sips",
        cost=cost,
        is_fallback=is_fallback,
        fidelity=fidelity,
        description=description,
        check_available=macos_native.has_sips,
        execute=lambda s, d, o, f=fmt: macos_native.convert_image_sips(s, d, f, o),
        command_preview=lambda s, d, o, f=fmt: macos_native.build_sips_cmd(s, d, f, o),
        terminal_only=terminal_only,
        supports_dpi=supports_dpi,
    )


def _magick_edge(
    source: str,
    target: str,
    cost: int,
    fidelity: FidelityClass,
    description: str,
    *,
    is_fallback: bool = True,
    terminal_only: bool = False,
    pass_source: bool = False,
    pass_target: bool = False,
) -> Edge:
    src_arg = source if pass_source else None
    dst_arg = target if pass_target else None
    return Edge(
        source=source,
        target=target,
        engine_name="magick",
        cost=cost,
        is_fallback=is_fallback,
        fidelity=fidelity,
        description=description,
        check_available=imagemagick.has_magick,
        execute=lambda s, d, o, sf=src_arg, tf=dst_arg: imagemagick.convert_magick(
            s, d, o, source_fmt=sf, target_fmt=tf
        ),
        command_preview=lambda s, d, o, sf=src_arg, tf=dst_arg: imagemagick.build_magick_cmd(
            s, d, o, source_fmt=sf, target_fmt=tf
        ),
        terminal_only=terminal_only,
    )


